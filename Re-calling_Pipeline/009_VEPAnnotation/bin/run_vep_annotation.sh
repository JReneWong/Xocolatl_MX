#!/usr/bin/env bash
# Module 009_VEPAnnotation — annotate 008_FilterVCF's PASS-only VCF with
# Ensembl VEP (offline cache) + ClinVar/gnomAD custom tracks.
#
# Deliberately identical to VCF_pipeline/002-VEPAnnotation's script (same
# flags, same custom tracks, same GRCh38_chr_synonyms.tsv fix) — see that
# module's own comments for the full reasoning behind each choice
# (contig-naming fix, why dbSNP/COSMIC are skipped, why gnomAD is
# AF-only). This is the Re-calling front's counterpart step, now that
# both fronts follow the same annotation methodology (team decision).
#
# One real difference worth flagging, not yet verified: VCF_pipeline's
# input VCF uses plain contig names (1, 2, X...) matching VEP's cache
# directly — --synonyms there only had to reconcile the chr-prefixed
# --fasta/--custom tracks against it. Our input here
# (008_FilterVCF's output) is chr-prefixed on the MAIN VCF itself, since
# 004_HaplotypeCaller called against the chr-prefixed Broad genome.
# --synonyms is documented to handle exactly this case too (translating
# the main input's contigs against the cache, not just secondary
# sources), but the team's earlier validation (a 2,174-variant chr1
# subset, confirmed gene/transcript/HGVSc/ClinVar fields populated
# correctly) tested the non-chr-prefixed-main-VCF case specifically —
# worth re-checking annotation completeness once this actually runs,
# since it's a new combination.
#
# --- Scattered per chromosome (restructured after 7 failed monolithic
# runs) ---
# The single whole-genome VEP invocation was killed by the OS repeatedly
# (survival times from ~1 min to ~77 min, no reproducible pattern).
# Investigated via cgroup v2 memory accounting (not just `free -h`, which
# reports page cache as freely reclaimable and looked fine): this
# terminal session's own cgroup had accumulated ~42GB of usage after
# many hours of heavy VCF/BAM/reference I/O, the dominant contributor on
# the host, ahead of every other desktop app combined — most likely
# page cache generated by our own file reads, not true pressure from
# something else. Root cause not proven with full certainty (no hard
# cgroup memory.max was ever set, so the exact kill trigger is still
# unconfirmed), but restarting the terminal (fresh cgroup, page cache
# reset) plus scattering this module the same way 004_HaplotypeCaller
# scatters HaplotypeCaller is the mitigation: even if something kills a
# run again, it can only cost one chromosome's worth of work (minutes),
# not the full callset (up to 77+ minutes lost per kill so far).
#
# Unlike 004_HaplotypeCaller, this doesn't need a separate bcftools split
# step to hand each contig its own input file: VEP's --chr flag does the
# same job as HaplotypeCaller's -L directly against the one shared input
# VCF ("select a subset of chromosomes to run the analysis on; any data
# not on this chromosome in the input will be skipped"). Per-contig
# outputs are gathered at the end with a plain bcftools concat (not -a —
# each contig's subset is already non-overlapping, and the CONTIGS array
# below is in the same reference-dictionary order the input VCF is
# already sorted in, so a naive concat preserves correct order).
#
# Run from anywhere:
#   bash Re-calling_Pipeline/009_VEPAnnotation/bin/run_vep_annotation.sh
#
# Override defaults with env vars, e.g.:
#   CPUS=8 bash Re-calling_Pipeline/009_VEPAnnotation/bin/run_vep_annotation.sh
#
# Safe to re-run: each contig and the final gather are skipped if their
# expected output already exists (set FORCE=1 to redo).

set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
MODULE_DIR="$PROJECT_ROOT/Re-calling_Pipeline/009_VEPAnnotation"
INPUT_DIR="$PROJECT_ROOT/Re-calling_Pipeline/008_FilterVCF/results"   # see data/README.txt — not a symlink on this exFAT+Linux setup
REF_DIR="$PROJECT_ROOT/references"

SAMPLE="WGS_EX2312012_HGWCNDSX7"
INPUT_VCF="$INPUT_DIR/${SAMPLE}.PASS.vcf.gz"

REFERENCE_GENOME="$REF_DIR/genome/Homo_sapiens_assembly38.fasta"
SYNONYMS="$REF_DIR/genome/GRCh38_chr_synonyms.tsv"
VEP_CACHE_DIR="$REF_DIR/vep_cache"
CLINVAR_FILE="$REF_DIR/clinvar/clinvar_GRCh38.raw.vcf.gz"   # non-chr-prefixed — matches VEP cache; --synonyms reconciles our chr-prefixed main VCF against it
GNOMAD_FILE="${GNOMAD_FILE:-$REF_DIR/gnomAD/gnomad.genomes.v3.1.2.short.vcf.gz}"   # chr-prefixed — needs SYNONYMS too, see note above

SPECIES="homo_sapiens"
CACHE_VERSION="116"   # matches installed ensembl-vep 116.1 and references/vep_cache/homo_sapiens/116_GRCh38
ASSEMBLY="GRCh38"

# Same primary-assembly contig list and order as 004_HaplotypeCaller —
# see that script's comment for why ALT/decoy/unplaced contigs are
# excluded (not strictly needed here since $INPUT_VCF is already
# restricted to what HaplotypeCaller called, but kept identical for
# consistency and so ordering matches for the final concat).
CONTIGS=(chr1 chr2 chr3 chr4 chr5 chr6 chr7 chr8 chr9 chr10 chr11 chr12 \
         chr13 chr14 chr15 chr16 chr17 chr18 chr19 chr20 chr21 chr22 \
         chrX chrY chrM)

CPUS="${CPUS:-4}"
MEM="${MEM:-n/a}"   # logged in the manifest only — VEP has no hard memory-cap flag; watch `free`/`top` during the run

source "$PROJECT_ROOT/common/manifest.sh"
CONTAINER="$(resolve_container "$PROJECT_ROOT")"

# data/ is just a documentation stub here (see data/README.txt) — point
# manifests at the real input so provenance is accurate, not at the empty
# placeholder.
export MANIFEST_INPUT_DIR="$INPUT_DIR"

if [ ! -f "$CONTAINER" ]; then
    echo "Error: $CONTAINER not found. Build it first (see README.md)." >&2
    exit 1
fi

for f in "$INPUT_VCF" "$REFERENCE_GENOME" "$SYNONYMS" "$CLINVAR_FILE" "$CLINVAR_FILE.tbi"; do
    if [ ! -e "$f" ]; then
        echo "Error: required file $f does not exist." >&2
        exit 1
    fi
done
if [ ! -d "$VEP_CACHE_DIR/$SPECIES/${CACHE_VERSION}_${ASSEMBLY}" ]; then
    echo "Error: VEP cache dir $VEP_CACHE_DIR/$SPECIES/${CACHE_VERSION}_${ASSEMBLY} does not exist." >&2
    exit 1
fi

CUSTOM_ARGS=(--custom "file=${CLINVAR_FILE},short_name=ClinVar,format=vcf,type=exact,coords=0,fields=CLNSIG%CLNREVSTAT")
if [ -n "$GNOMAD_FILE" ]; then
    if [ ! -e "$GNOMAD_FILE" ] || [ ! -e "$GNOMAD_FILE.tbi" ]; then
        echo "Error: GNOMAD_FILE=$GNOMAD_FILE or its .tbi index does not exist." >&2
        exit 1
    fi
    CUSTOM_ARGS+=(--custom "file=${GNOMAD_FILE},short_name=gnomAD,format=vcf,type=exact,coords=0,fields=AF")
else
    echo "Warning: GNOMAD_FILE not set — no gnomAD file found on this drive." >&2
    echo "         Annotating without population allele frequency. See script header." >&2
fi

mkdir -p "$MODULE_DIR/results"

CONTIG_VCFS=()
for CONTIG in "${CONTIGS[@]}"; do
    OUT_VCF="$MODULE_DIR/results/vep_${SAMPLE}.PASS.${CONTIG}.vcf.gz"
    CONTIG_VCFS+=("$OUT_VCF")

    if [ -s "$OUT_VCF" ] && [ -s "$OUT_VCF.tbi" ] && [ "${FORCE:-0}" != "1" ]; then
        echo "$OUT_VCF already present — skipping (FORCE=1 to redo)."
        continue
    fi

    # "${CUSTOM_ARGS[@]}" below expands to ClinVar always, plus gnomAD only
    # if GNOMAD_FILE is set — built above. --chr restricts this invocation
    # to one chromosome of the shared, un-split $INPUT_VCF (see header
    # comment — same role as HaplotypeCaller's -L).
    run_and_log "$MODULE_DIR" "$CONTAINER" "$CPUS" "$MEM" -- \
        apptainer exec --bind "$PROJECT_ROOT:$PROJECT_ROOT" "$CONTAINER" \
        vep -i "$INPUT_VCF" \
            --chr "$CONTIG" \
            --cache_version "$CACHE_VERSION" \
            --vcf \
            -t SO \
            --format vcf \
            --buffer_size 50000 \
            --offline \
            --symbol \
            -o "$OUT_VCF" \
            --cache \
            --dir "$VEP_CACHE_DIR" \
            --species "$SPECIES" \
            --biotype \
            --sift b \
            --flag_pick_allele_gene \
            --canonical \
            --hgvs \
            --shift_hgvs 1 \
            --mane \
            --numbers \
            --protein \
            --polyphen p \
            --transcript_version \
            --domains \
            --assembly "$ASSEMBLY" \
            --fasta "$REFERENCE_GENOME" \
            --synonyms "$SYNONYMS" \
            --compress_output bgzip \
            "${CUSTOM_ARGS[@]}" \
            --show_ref_allele \
            --fork "$CPUS" \
            --force_overwrite

    run_and_log "$MODULE_DIR" "$CONTAINER" "1" "n/a" -- \
        apptainer exec --bind "$PROJECT_ROOT:$PROJECT_ROOT" "$CONTAINER" \
        tabix -f -p vcf "$OUT_VCF"
done

MERGED_VCF="$MODULE_DIR/results/vep_${SAMPLE}.PASS.vcf.gz"
if [ -s "$MERGED_VCF" ] && [ -s "$MERGED_VCF.tbi" ] && [ "${FORCE:-0}" != "1" ]; then
    echo "$MERGED_VCF already present — skipping (FORCE=1 to redo)."
else
    CONCAT_CMD="set -euo pipefail; bcftools concat -Oz -o '$MERGED_VCF' $(printf "'%s' " "${CONTIG_VCFS[@]}") \
        && bcftools index -t '$MERGED_VCF'"

    run_and_log "$MODULE_DIR" "$CONTAINER" "1" "n/a" -- \
        apptainer exec --bind "$PROJECT_ROOT:$PROJECT_ROOT" "$CONTAINER" \
        bash -c "$CONCAT_CMD"
fi

echo
echo "Done. Annotated VCF (all contigs gathered): $MERGED_VCF"
echo "Per-contig annotated VCFs kept in: $MODULE_DIR/results/vep_${SAMPLE}.PASS.<contig>.vcf.gz"
